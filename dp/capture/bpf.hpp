#pragma once

#include <cstddef>
#include <cstdint>
#include <string>
#include <vector>
#include <linux/filter.h> // Linux BPF library

namespace dp {
namespace capture {

    // Forward declarations for BPF compiler API
    struct BPFCompileResult;

    /*
    Initial supported expressions:

        tcp
        udp
        icmp
        arp
        host 192.168.1.10
        port 443
        tcp and port 443
        tcp or udp
        not arp
        (tcp or udp) and port 443

    This module only compiles filter expressions. It does not create
    sockets, attach filters, capture packets, or access the ring buffer.
*/

/*
    Owns the classic-BPF instructions generated by the compiler.

    The vector owns the instruction memory. SocketCapture can later
    create a temporary sock_fprog that points to this vector when
    calling SO_ATTACH_FILTER.
*/


struct BPFProgram {
    std::vector<sock_filter> instructions;

    BPFProgram() = default; // default constructor
    BPFProgram(const BPFProgram&) = delete; // copy constructor deleted
    BPFProgram(BPFProgram&&) = default; // move constructor defaulted
    BPFProgram& operator=(const BPFProgram&) = delete; // copy assignment deleted
    BPFProgram& operator=(BPFProgram&&) = default; // move assignment defaulted

    // Parses, validates, and compiles a filter expression into
    // classic-BPF instructions.
    static BPFCompileResult compile(const std::string& expr);

    bool empty() const noexcept { return instructions.empty(); }
    std::size_t size() const noexcept { return instructions.size(); }

};

enum class BPFCompileError {
    NONE = 0,
    EMPTY_EXPRESSION,
    UNEXPECTED_TOKEN,
    UNKNOWN_KEYWORD,
    MISSING_OPERAND,
    INVALID_ADDRESS,
    INVALID_PORT,
    PORT_OUT_OF_RANGE,
    UNSUPPORTED_EXPRESSION,
    PROGRAM_TOO_LARGE,
    INTERNAL_ERROR
};

struct BPFCompileResult {
    // A failed result must not be attached to a socket.
    // A successful result contains a generated classic-BPF program.
    bool success = false;
    BPFProgram program;
    BPFCompileError error = BPFCompileError::NONE;
    std::string message;
};



} // namespace capture
} // namespace dp
